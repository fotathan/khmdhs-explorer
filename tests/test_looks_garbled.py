def test_flags_full_scramble_font():
    assert looks_garbled(GARBLED_SCRAMBLE) is True


def test_flags_third_font_family():
    assert looks_garbled(GARBLED_THIRD_FONT) is True


def test_reserved_codepoint_alone_is_enough():
    """U+03A2 is unassigned in the Greek block — no real Greek text can contain
    it. Every broken font seen maps capital Σ onto it, so a handful is
    conclusive even where the surrounding text looks otherwise sane."""
    assert looks_garbled("ΝΟΜΟ\u03a2 ΡΕΘΤΜΝΗ\u03a2 ΔΗΜΟ\u03a2 ΜΤΛΟΠΟΣΑΜΟΤ") is True
    # ...but one or two must not condemn an otherwise clean document.
    assert looks_garbled("ΝΟΜΟ\u03a2 ΡΕΘΥΜΝΗΣ " + CLEAN_PROSE) is False


def test_non_final_sigma_is_impossible_in_real_greek():
    """ς only ever ends a word. Mid-word ς over a real volume of text means the
    font mapped σ onto it."""
    assert looks_garbled("ςυνολικοφ προχπολογιςμοφ ςυμπεριλαμβανομζνου " * 12) is True


def test_theta_outnumbering_eta_is_flagged():
    """Real Greek runs ~0.27 θ per η; the swapped fonts invert that, because
    every η in the document arrives as θ."""
    assert looks_garbled("τθν πλθρωμι τθσ επιχείρθςθσ κατά τθν θμερομθνία " * 12) is True


